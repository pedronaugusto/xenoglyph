//! The security tables (UTS #39): each code point's confusable prototype,
//! its Identifier_Type values (Identifier_Status follows from them), and
//! the zero of each decimal digit system. Part of the generator; see
//! generate.zig.
const std = @import("std");
const generate = @import("generate.zig");

const Allocator = std.mem.Allocator;

/// Identifier_Type's values, in the order of `IdentifierType`'s fields.
const types = [_][]const u8{
    "Not_Character", "Deprecated", "Default_Ignorable", "Not_NFKC",    "Not_XID",   "Exclusion",
    "Obsolete",      "Technical",  "Uncommon_Use",      "Limited_Use", "Inclusion", "Recommended",
};
const inclusion = 10;
const recommended = 11;

pub fn securityFile(gpa: Allocator, ucd: generate.Ucd) ![]const u8 {
    var out: std.Io.Writer.Allocating = .init(gpa);
    const w = &out.writer;
    try w.print(
        \\//! UTS #39's data for Unicode {s}, from ucd/security (confusables.txt, IdentifierType.txt, IdentifierStatus.txt) and UnicodeData.txt's decimal digits.
        \\//!
        \\//! Generated by tools/generate.zig; `bay ucd` writes it again and
        \\//! `bay check-tables` checks it. Do not edit. The Unicode data is under
        \\//! the Unicode License v3: see ../UNICODE-LICENSE.txt.
        \\
        \\const lookup = @import("../table.zig");
        \\
        \\
    , .{generate.version});

    // Prototypes: one code point inline, longer ones as a run of `prototypes`.
    const values = try generate.filled(gpa, u32, 0);
    var prototypes: std.ArrayList(u21) = .empty;
    var lines: generate.Lines = .init(try ucd.read("security/confusables.txt"));
    while (try lines.next()) |l| {
        if (l.first != l.last or !std.mem.eql(u8, l.field(1), "MA")) return error.BadConfusable;
        var target: std.ArrayList(u21) = .empty;
        var fields = std.mem.tokenizeScalar(u8, l.field(0), ' ');
        while (fields.next()) |f| try target.append(gpa, try std.fmt.parseInt(u21, f, 16));
        if (target.items.len == 0 or target.items.len > 31) return error.BadConfusable;
        if (values[l.first] != 0) return error.DuplicateConfusable;
        if (target.items.len == 1) {
            values[l.first] = (@as(u32, target.items[0]) << 1) | 1;
        } else {
            values[l.first] = @intCast((prototypes.items.len << 6) | (target.items.len << 1));
            try prototypes.appendSlice(gpa, target.items);
        }
    }
    try w.writeAll(
        \\/// Each code point's prototype (confusables.txt). With bit 0 set, one
        \\/// code point, in bits 1 to 21. Otherwise a run of `prototypes`,
        \\/// starting at bits 6 to 31 and as long as bits 1 to 5 say. 0: the code
        \\/// point is its own prototype.
        \\
    );
    try generate.writeShape(w, try generate.shape(gpa, values, 4, .smallest), "confusables", "u32");
    try w.print("\n/// The prototypes of more than one code point.\npub const prototypes = [{d}]u21{{\n", .{prototypes.items.len});
    try generate.numbers(w, prototypes.items);
    try w.writeAll("};\n\n");

    // Identifier_Type, a set of values; Identifier_Status is Allowed exactly
    // where it holds Inclusion or Recommended.
    const sets = try generate.filled(gpa, u32, 1 << 0);
    lines = .init(try ucd.read("security/IdentifierType.txt"));
    while (try lines.next()) |l| {
        var set: u32 = 0;
        var names = std.mem.tokenizeScalar(u8, l.field(0), ' ');
        while (names.next()) |name| {
            const k = for (types, 0..) |t, k| {
                if (std.mem.eql(u8, t, name)) break k;
            } else return error.UnknownIdentifierType;
            set |= @as(u32, 1) << @intCast(k);
        }
        for (sets[l.first .. l.last + 1]) |*s| s.* = set;
    }
    const allowed_mask: u32 = (1 << inclusion) | (1 << recommended);
    var allowed = try generate.filled(gpa, bool, false);
    lines = .init(try ucd.read("security/IdentifierStatus.txt"));
    while (try lines.next()) |l| {
        if (!std.mem.eql(u8, l.field(0), "Allowed")) return error.UnknownIdentifierStatus;
        for (allowed[l.first .. l.last + 1]) |*a| a.* = true;
    }
    for (sets, allowed) |s, a| if ((s & allowed_mask != 0) != a) return error.StatusDisagreesWithType;
    try w.writeAll(
        \\/// Each code point's Identifier_Type values, a bit each in the order of
        \\/// `security.IdentifierType`'s fields (IdentifierType.txt; Not_Character
        \\/// where it lists none). Identifier_Status is Allowed exactly where
        \\/// Inclusion or Recommended is among them, as IdentifierStatus.txt says.
        \\
    );
    try generate.writeShape(w, try generate.shape(gpa, sets, 2, .smallest), "identifier_types", "u16");

    // The zero of each run of decimal digits: a digit's code point less its value.
    var zeros: std.ArrayList(u21) = .empty;
    var data = std.mem.splitScalar(u8, try ucd.read("UnicodeData.txt"), '\n');
    while (data.next()) |line| {
        if (line.len == 0) continue;
        var fields = std.mem.splitScalar(u8, line, ';');
        const cp = try std.fmt.parseInt(u21, fields.next().?, 16);
        _ = fields.next();
        if (!std.mem.eql(u8, fields.next() orelse return error.BadUnicodeData, "Nd")) continue;
        for (0..3) |_| _ = fields.next();
        const value = try std.fmt.parseInt(u21, fields.next() orelse return error.BadUnicodeData, 10);
        if (value == 0) try zeros.append(gpa, cp) else if (zeros.items.len == 0 or zeros.items[zeros.items.len - 1] != cp - value) return error.DigitsOutOfRun;
    }
    try w.writeAll(
        \\
        \\/// The zero of each decimal digit system (General_Category Nd), in
        \\/// order: every run of digits starts with its zero and goes up by one.
        \\pub const decimal_zeros = [_]u21{
        \\
    );
    try generate.numbers(w, zeros.items);
    try w.writeAll("};\n");
    return out.toOwnedSlice();
}
