pub fn encodingFile(gpa: Allocator, ucd: generate.Ucd) ![]const u8 {
    var out: std.Io.Writer.Allocating = .init(gpa);
    const w = &out.writer;
    try w.writeAll(
        \\//! The WHATWG Encoding Standard's labels and indexes, and IBM code page 437, from ucd/whatwg (encodings.json, index-*.txt, CP437.TXT).
        \\//!
        \\//! Generated by tools/generate.zig; `bay ucd` writes it again and
        \\//! `bay check-tables` checks it. Do not edit. The Encoding Standard's
        \\//! data is under the BSD 3-Clause licence: see ../../ucd/whatwg/LICENSE-WHATWG.
        \\
        \\const lookup = @import("../table.zig");
        \\
        \\
    );
    try labels(gpa, ucd, w);

    // Single-byte: bytes 0x80 to 0xFF, 0 where a byte maps to nothing.
    try w.print("/// Bytes 0x80 to 0xFF of each single-byte encoding, in `classes.Encoding` order from IBM866, then CP437; 0 where the byte maps to nothing.\npub const single_byte = [{d}][128]u16{{\n", .{single_byte.len + 1});
    var tables: [single_byte.len + 1][128]u16 = undefined;
    for (single_byte, 0..) |e, k| {
        tables[k] = @splat(0);
        const entries = try index(gpa, ucd, e[1]);
        for (entries) |entry| tables[k][entry.pointer] = @intCast(entry.code_point);
    }
    tables[single_byte.len] = try cp437(gpa, ucd);
    for (tables) |t| try array(w, u16, &t, "    .{", "},\n");
    try w.writeAll("};\n\n");
    try w.print("/// Each single-byte encoding's mapped code points, sorted, each with its byte: what its encoder searches.\npub const single_byte_encode = [{d}][]const [2]u16{{\n", .{single_byte.len + 1});
    for (tables) |t| {
        var pairs: std.ArrayList([2]u16) = .empty;
        for (t, 0..) |cp, b| if (cp != 0) try pairs.append(gpa, .{ cp, @intCast(b + 0x80) });
        std.mem.sort([2]u16, pairs.items, {}, struct {
            fn less(_: void, a: [2]u16, b: [2]u16) bool {
                return a[0] < b[0];
            }
        }.less);
        try w.writeAll("    &.{");
        for (pairs.items, 0..) |p, n| try w.print("{s}.{{ 0x{x}, 0x{x} }}", .{ if (n == 0) "" else ", ", p[0], p[1] });
        try w.writeAll("},\n");
    }
    try w.writeAll("};\n\n");

    // Multi-byte decoding indexes, by pointer, 0 where a pointer maps to nothing.
    const jis0208 = try dense(gpa, try index(gpa, ucd, "jis0208"));
    const jis0212 = try dense(gpa, try index(gpa, ucd, "jis0212"));
    const euc_kr = try dense(gpa, try index(gpa, ucd, "euc-kr"));
    const gb18030 = try dense(gpa, try index(gpa, ucd, "gb18030"));
    const big5 = try dense(gpa, try index(gpa, ucd, "big5"));
    const katakana = try dense(gpa, try index(gpa, ucd, "iso-2022-jp-katakana"));
    try decodeIndex(w, "jis0208", "u16", jis0208);
    try decodeIndex(w, "jis0212", "u16", jis0212);
    try decodeIndex(w, "euc_kr", "u16", euc_kr);
    try decodeIndex(w, "gb18030", "u16", gb18030);
    try decodeIndex(w, "big5", "u21", big5);
    try decodeIndex(w, "katakana", "u16", katakana);
    try w.writeAll("/// The gb18030 ranges: each pointer that starts one, with its code point.\npub const gb18030_ranges = [_][2]u32{\n");
    for (try index(gpa, ucd, "gb18030-ranges")) |r| try w.print("    .{{ {d}, 0x{x} }},\n", .{ r.pointer, r.code_point });
    try w.writeAll("};\n\n");

    // Encoding: each code point's pointer, plus one, by the standard's rules.
    try encodeTrie(gpa, w, "jis0208_encode", "index jis0208 pointer: the first pointer", jis0208, .first, null);
    try encodeTrie(gpa, w, "shift_jis_encode", "index Shift_JIS pointer: the first pointer outside 8272 to 8835", jis0208, .first, .{ 8272, 8835 });
    try encodeTrie(gpa, w, "euc_kr_encode", "index EUC-KR pointer", euc_kr, .first, null);
    try encodeTrie(gpa, w, "gb18030_encode", "index gb18030 pointer", gb18030, .first, null);
    try encodeTrie(gpa, w, "big5_encode", "index Big5 pointer: pointers below (0xA1 - 0x81) * 157 excluded, the last pointer for U+2550, U+255E, U+2561, U+256A, U+5341 and U+5345, else the first", big5, .big5, .{ 0, (0xa1 - 0x81) * 157 - 1 });
    return out.toOwnedSlice();
}

const Entry = struct { pointer: u32, code_point: u21 };

/// An index file's pointers and code points.
fn index(gpa: Allocator, ucd: generate.Ucd, name: []const u8) ![]const Entry {
    const text = try ucd.read(try gpa.print("whatwg/index-{s}.txt", .{name}));
    var out: std.ArrayList(Entry) = .empty;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = generate.trim(if (std.mem.findScalar(u8, raw, '#')) |h| raw[0..h] else raw);
        if (line.len == 0) continue;
        var fields = std.mem.tokenizeAny(u8, line, " \t");
        const pointer = try std.fmt.parseInt(u32, fields.next().?, 10);
        const cp_text = fields.next().?;
        const code_point = try std.fmt.parseInt(u21, cp_text[2..], 16);
        try out.append(gpa, .{ .pointer = pointer, .code_point = code_point });
    }
    return out.toOwnedSlice(gpa);
}

/// CP437.TXT's bytes 0x80 to 0xFF.
fn cp437(gpa: Allocator, ucd: generate.Ucd) ![128]u16 {
    _ = gpa;
    var out: [128]u16 = @splat(0);
    var lines = std.mem.splitScalar(u8, try ucd.read("whatwg/CP437.TXT"), '\n');
    while (lines.next()) |raw| {
        const line = generate.trim(if (std.mem.findScalar(u8, raw, '#')) |h| raw[0..h] else raw);
        if (line.len == 0) continue;
        var fields = std.mem.tokenizeAny(u8, line, " \t");
        const first = fields.next().?;
        // The file ends with a DOS end-of-file byte.
        if (!std.mem.startsWith(u8, first, "0x")) continue;
        const byte = try std.fmt.parseInt(u8, first[2..], 16);
        const cp = try std.fmt.parseInt(u16, fields.next().?[2..], 16);
        if (byte >= 0x80) out[byte - 0x80] = cp else if (cp != byte) return error.Cp437NotAscii;
    }
    for (out) |cp| if (cp == 0) return error.Cp437Incomplete;
    return out;
}

/// An index as an array by pointer, 0 where a pointer maps to nothing.
fn dense(gpa: Allocator, entries: []const Entry) ![]u21 {
    var top: usize = 0;
    for (entries) |e| top = @max(top, e.pointer + 1);
    const out = try gpa.alloc(u21, top);
    @memset(out, 0);
    for (entries) |e| out[e.pointer] = e.code_point;
    return out;
}

fn decodeIndex(w: *std.Io.Writer, name: []const u8, comptime T: []const u8, values: []const u21) !void {
    try w.print("/// index {s}, by pointer; 0 where a pointer maps to nothing.\npub const {s} = [{d}]{s}{{\n", .{ name, name, values.len, T });
    var line: usize = 0;
    for (values, 0..) |v, n| {
        if (line == 0) try w.writeAll("   ");
        try w.print(" 0x{x},", .{v});
        line += 1;
        if (line == 16 or n + 1 == values.len) {
            try w.writeByte('\n');
            line = 0;
        }
    }
    try w.writeAll("};\n\n");
}

const Pick = enum { first, big5 };

/// The trie from each code point to its pointer plus one (0: none), the
/// pointer the standard's encoder takes: the first, or for Big5 the last
/// for six code points, skipping `excluded` pointers.
fn encodeTrie(gpa: Allocator, w: *std.Io.Writer, name: []const u8, what: []const u8, values: []const u21, pick: Pick, excluded: ?[2]u32) !void {
    const raw = try gpa.alloc(u32, generate.code_points);
    @memset(raw, 0);
    for (values, 0..) |cp, p| {
        if (cp == 0) continue;
        if (excluded) |x| if (p >= x[0] and p <= x[1]) continue;
        const last = pick == .big5 and switch (cp) {
            0x2550, 0x255e, 0x2561, 0x256a, 0x5341, 0x5345 => true,
            else => false,
        };
        if (raw[cp] == 0 or last) raw[cp] = @intCast(p + 1);
    }
    try w.print("/// {s}, plus one; 0 where a code point has none.\n", .{what});
    try generate.writeShape(w, try generate.shape(gpa, raw, 2, .smallest), name, "u16");
    try w.writeByte('\n');
}

fn array(w: *std.Io.Writer, comptime T: type, values: []const T, open: []const u8, close: []const u8) !void {
    try w.writeAll(open);
    for (values, 0..) |v, n| try w.print("{s}0x{x}", .{ if (n == 0) "" else ", ", v });
    try w.writeAll(close);
}

/// encodings.json's labels, sorted, each with its encoding.
fn labels(gpa: Allocator, ucd: generate.Ucd, w: *std.Io.Writer) !void {
    const Json = []const struct { encodings: []const struct { labels: []const []const u8, name: []const u8 }, heading: []const u8 };
    const parsed = try std.json.parseFromSliceLeaky(Json, gpa, try ucd.read("whatwg/encodings.json"), .{});
    const Label = struct { label: []const u8, encoding: Encoding };
    var list: std.ArrayList(Label) = .empty;
    var names: [@typeInfo(Encoding).@"enum".field_names.len][]const u8 = @splat("");
    var k: usize = 0;
    for (parsed) |heading| for (heading.encodings) |e| {
        const encoding: Encoding = @fromBackingInt(@intCast(k));
        names[k] = e.name;
        k += 1;
        for (e.labels) |l| try list.append(gpa, .{ .label = l, .encoding = encoding });
    };
    if (k + 1 != names.len) return error.EncodingsDiffer;
    names[k] = "IBM437";
    std.mem.sort(Label, list.items, {}, struct {
        fn less(_: void, a: Label, b: Label) bool {
            return std.mem.order(u8, a.label, b.label) == .lt;
        }
    }.less);
    try w.writeAll("/// Each encoding's name, in `classes.Encoding` order.\npub const names = [_][]const u8{\n");
    for (names) |n| try w.print("    \"{s}\",\n", .{n});
    try w.writeAll("};\n\n/// Every label, sorted, with its encoding's position in `classes.Encoding`.\npub const labels = [_]struct { []const u8, u8 }{\n");
    for (list.items) |l| try w.print("    .{{ \"{s}\", {d} }},\n", .{ l.label, @backingInt(l.encoding) });
    try w.writeAll("};\n\n");
}
