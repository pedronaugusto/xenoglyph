//! The character encoding tables: the WHATWG Encoding Standard's labels and
//! indexes (ucd/whatwg/encodings.json and index-*.txt), and IBM code page 437
//! (ucd/whatwg/CP437.TXT). Decoding indexes are arrays by pointer; encoding
//! is a trie over code points, xenoglyph's one table format, from each code
//! point to the pointer the standard's encoder takes. Part of the generator;
//! see generate.zig.
const std = @import("std");
const classes = @import("classes");
const generate = @import("generate.zig");

const Allocator = std.mem.Allocator;
const Encoding = classes.Encoding;

