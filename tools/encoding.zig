/// index Shift_JIS pointer differs from index jis0208 pointer only for a code
/// point whose first pointer is in 8272 to 8835 (NEC's selection of IBM
/// extensions, also at 10716 to 11103): each such code point, sorted, with
/// its first pointer outside that range plus one, 0 where it has none.
fn shiftJisAlternates(gpa: Allocator, w: *std.Io.Writer, jis0208: []const u21) !void {
    var list: std.ArrayList([2]u32) = .empty;
    for (jis0208, 0..) |cp, p| {
        if (cp == 0 or p < 8272 or p > 8835) continue;
        if (std.mem.findScalar(u21, jis0208[0..p], cp) != null) continue;
        var other: u32 = 0;
        for (jis0208[8836..], 8836..) |c, q| if (c == cp) {
            other = @intCast(q + 1);
            break;
        };
        try list.append(gpa, .{ cp, other });
    }
    std.mem.sort([2]u32, list.items, {}, struct {
        fn less(_: void, a: [2]u32, b: [2]u32) bool {
            return a[0] < b[0];
        }
    }.less);
    try w.writeAll("/// index Shift_JIS pointer where it is not index jis0208 pointer: each code\n/// point whose first pointer is in 8272 to 8835, sorted, with its first pointer\n/// outside them plus one; 0 where it has none.\npub const shift_jis_alternates = [_][2]u16{\n");
    for (list.items) |a| try w.print("    .{{ 0x{x}, {d} }},\n", .{ a[0], a[1] });
    try w.writeAll("};\n\n");
}

/// An index file's pointers and code points.
fn index(gpa: Allocator, ucd: generate.Ucd, name: []const u8) ![]const Entry {
    const text = try ucd.read(try gpa.print("whatwg/index-{s}.txt", .{name}));
    var out: std.ArrayList(Entry) = .empty;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = generate.trim(if (std.mem.findScalar(u8, raw, '#')) |h| raw[0..h] else raw);
        if (line.len == 0) continue;
        var fields = std.mem.tokenizeAny(u8, line, " \t");
        const pointer = try std.fmt.parseInt(u32, fields.next().?, 10);
        const cp_text = fields.next().?;
        const code_point = try std.fmt.parseInt(u21, cp_text[2..], 16);
        try out.append(gpa, .{ .pointer = pointer, .code_point = code_point });
    }
    return out.toOwnedSlice(gpa);
}

/// CP437.TXT's bytes 0x80 to 0xFF.
fn cp437(gpa: Allocator, ucd: generate.Ucd) ![128]u16 {
    _ = gpa;
    var out: [128]u16 = @splat(0);
    var lines = std.mem.splitScalar(u8, try ucd.read("whatwg/CP437.TXT"), '\n');
    while (lines.next()) |raw| {
        const line = generate.trim(if (std.mem.findScalar(u8, raw, '#')) |h| raw[0..h] else raw);
        if (line.len == 0) continue;
        var fields = std.mem.tokenizeAny(u8, line, " \t");
        const first = fields.next().?;
        // The file ends with a DOS end-of-file byte.
        if (!std.mem.startsWith(u8, first, "0x")) continue;
        const byte = try std.fmt.parseInt(u8, first[2..], 16);
        const cp = try std.fmt.parseInt(u16, fields.next().?[2..], 16);
        if (byte >= 0x80) out[byte - 0x80] = cp else if (cp != byte) return error.Cp437NotAscii;
    }
    for (out) |cp| if (cp == 0) return error.Cp437Incomplete;
    return out;
}

/// An index as an array by pointer, 0 where a pointer maps to nothing.
fn dense(gpa: Allocator, entries: []const Entry) ![]u21 {
    var top: usize = 0;
    for (entries) |e| top = @max(top, e.pointer + 1);
    const out = try gpa.alloc(u21, top);
    @memset(out, 0);
    for (entries) |e| out[e.pointer] = e.code_point;
    return out;
}

fn decodeIndex(w: *std.Io.Writer, name: []const u8, comptime T: []const u8, values: []const u21) !void {
    try w.print("/// index {s}, by pointer; 0 where a pointer maps to nothing.\npub const {s} = [{d}]{s}{{\n", .{ name, name, values.len, T });
    var line: usize = 0;
    for (values, 0..) |v, n| {
        if (line == 0) try w.writeAll("   ");
        try w.print(" 0x{x},", .{v});
        line += 1;
        if (line == 16 or n + 1 == values.len) {
            try w.writeByte('\n');
            line = 0;
        }
    }
    try w.writeAll("};\n\n");
}

const Pick = enum { first, big5 };

/// A code point and the two bytes the standard gives it outside its index.
const Extra = struct { u21, [2]u8 };

/// The trie from each code point to its pointer plus one (0: none), the
/// pointer the standard's encoder takes: the first, or for Big5 the last
/// for six code points, skipping `excluded` pointers.
fn encodeTrie(gpa: Allocator, w: *std.Io.Writer, name: []const u8, what: []const u8, values: []const u21, pick: Pick, excluded: ?[2]u32, extra: []const Extra) !void {
    const raw = try gpa.alloc(u32, generate.code_points);
    @memset(raw, 0);
    for (values, 0..) |cp, p| {
        if (cp == 0) continue;
        if (excluded) |x| if (p >= x[0] and p <= x[1]) continue;
        const last = pick == .big5 and switch (cp) {
            0x2550, 0x255e, 0x2561, 0x256a, 0x5341, 0x5345 => true,
            else => false,
        };
        if (raw[cp] == 0 or last) raw[cp] = @intCast(p + 1);
    }
    // Code points given bytes in the standard's prose rather than its index
    // (only gb18030's, whose bytes are the lead and trail of a pointer).
    for (extra) |x| {
        if (raw[x[0]] != 0) return error.ExtraHasPointer;
        const trail_offset: u32 = if (x[1][1] < 0x7f) 0x40 else 0x41;
        raw[x[0]] = (@as(u32, x[1][0]) - 0x81) * 190 + (x[1][1] - trail_offset) + 1;
    }
    try w.print("/// {s}, plus one; 0 where a code point has none.\n", .{what});
    try generate.writeShape(w, try generate.shape(gpa, raw, 2, .smallest), name, "u16");
    try w.writeByte('\n');
}

fn array(w: *std.Io.Writer, comptime T: type, values: []const T, open: []const u8, close: []const u8) !void {
    try w.writeAll(open);
    for (values, 0..) |v, n| try w.print("{s}0x{x}", .{ if (n == 0) "" else ", ", v });
    try w.writeAll(close);
}

/// encodings.json's labels, sorted, each with its encoding.
fn labels(gpa: Allocator, ucd: generate.Ucd, w: *std.Io.Writer) !void {
    const Json = []const struct { encodings: []const struct { labels: []const []const u8, name: []const u8 }, heading: []const u8 };
    const parsed = try std.json.parseFromSliceLeaky(Json, gpa, try ucd.read("whatwg/encodings.json"), .{});
    const Label = struct { label: []const u8, encoding: Encoding };
    var list: std.ArrayList(Label) = .empty;
    var names: [@typeInfo(Encoding).@"enum".field_names.len][]const u8 = @splat("");
    var k: usize = 0;
    for (parsed) |heading| for (heading.encodings) |e| {
        const encoding: Encoding = @fromBackingInt(@intCast(k));
        names[k] = e.name;
        k += 1;
        for (e.labels) |l| try list.append(gpa, .{ .label = l, .encoding = encoding });
    };
    if (k + 1 != names.len) return error.EncodingsDiffer;
    names[k] = "IBM437";
    std.mem.sort(Label, list.items, {}, struct {
        fn less(_: void, a: Label, b: Label) bool {
            return std.mem.order(u8, a.label, b.label) == .lt;
        }
    }.less);
    try w.writeAll("/// Each encoding's name, in `classes.Encoding` order.\npub const names = [_][]const u8{\n");
    for (names) |n| try w.print("    \"{s}\",\n", .{n});
    try w.writeAll("};\n\n/// Every label, sorted, with its encoding's position in `classes.Encoding`.\npub const labels = [_]struct { []const u8, u8 }{\n");
    for (list.items) |l| try w.print("    .{{ \"{s}\", {d} }},\n", .{ l.label, @backingInt(l.encoding) });
    try w.writeAll("};\n\n");
}
