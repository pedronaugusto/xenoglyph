//! The bidi tables (UAX #9) beyond Bidi_Class, which the IDNA record holds:
//! each paired bracket with the opening bracket its pair is matched by, up
//! to canonical equivalence (BD16), and each code point's mirroring glyph.
//! Part of the generator; see generate.zig.
const std = @import("std");
const generate = @import("generate.zig");
const mappings = @import("mappings.zig");

const Allocator = std.mem.Allocator;

pub fn bidiFile(gpa: Allocator, ucd: generate.Ucd, d: mappings.UnicodeData) ![]const u8 {
    var out: std.Io.Writer.Allocating = .init(gpa);
    const w = &out.writer;
    try w.print(
        \\//! The paired brackets and mirroring glyphs of UAX #9, from the Unicode Character Database {s} (BidiBrackets.txt, BidiMirroring.txt, UnicodeData.txt).
        \\//!
        \\//! Generated by tools/generate.zig; `bay generate` writes it again and
        \\//! `bay check-tables` checks it. Do not edit. The Unicode data is under
        \\//! the Unicode License v3: see ../UNICODE-LICENSE.txt.
        \\
        \\/// A paired bracket: `pair` is Bidi_Paired_Bracket, and `id` the opening
        \\/// bracket of the pair after its canonical decomposition, which a closing
        \\/// bracket matches an opening one by (BD16).
        \\pub const Bracket = struct {{ code_point: u21, pair: u21, id: u21, opening: bool }};
        \\
        \\/// Every paired bracket, by code point.
        \\pub const brackets = [_]Bracket{{
        \\
    , .{generate.version});
    var lines: generate.Lines = .init(try ucd.read("BidiBrackets.txt"));
    while (try lines.next()) |l| {
        const pair = try std.fmt.parseInt(u21, l.field(0), 16);
        const opening = std.mem.eql(u8, l.field(1), "o");
        if (!opening and !std.mem.eql(u8, l.field(1), "c")) return error.UnknownBracketType;
        const opener = if (opening) l.first else pair;
        try w.print("    .{{ .code_point = 0x{x}, .pair = 0x{x}, .id = 0x{x}, .opening = {} }},\n", .{ l.first, pair, canonical(d, opener), opening });
    }
    try w.writeAll(
        \\};
        \\
        \\/// Every code point with a Bidi_Mirroring_Glyph, by code point, and the glyph.
        \\pub const mirrors = [_][2]u21{
        \\
    );
    // The file is not in code point order everywhere; the list is, for a binary search.
    var mirrors: std.ArrayList([2]u21) = .empty;
    lines = .init(try ucd.read("BidiMirroring.txt"));
    while (try lines.next()) |l| try mirrors.append(gpa, .{ l.first, try std.fmt.parseInt(u21, l.field(0), 16) });
    std.mem.sort([2]u21, mirrors.items, {}, struct {
        fn less(_: void, a: [2]u21, b: [2]u21) bool {
            return a[0] < b[0];
        }
    }.less);
    for (mirrors.items) |m| try w.print("    .{{ 0x{x}, 0x{x} }},\n", .{ m[0], m[1] });
    try w.writeAll("};\n");
    return out.toOwnedSlice();
}

/// A bracket's singleton canonical decomposition, or itself: U+2329 is U+3008.
fn canonical(d: mappings.UnicodeData, cp: u21) u21 {
    const raw = d.decomposition[cp] orelse return cp;
    if (raw.compatibility or raw.code_points.len != 1) return cp;
    return raw.code_points[0];
}
