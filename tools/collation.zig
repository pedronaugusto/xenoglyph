//! The collation tables (UTS #10 with CLDR's root collation): each code
//! point's collation elements, the contractions, and what the implicit
//! weights are computed from. Part of the generator; see generate.zig.
//!
//! Entries for text that is not in NFD are left out: the collator reads its
//! input in NFD (UTS #10 step 1), so a precomposed character's entry would
//! never be looked up.
const std = @import("std");
const generate = @import("generate.zig");
const mappings = @import("mappings.zig");

const Allocator = std.mem.Allocator;

/// The longest contraction allkeys_CLDR.txt holds, in code points.
const max_contraction = 3;

const Entry = struct { code_points: []const u21, elements: []const u32 };

pub fn collationFile(gpa: Allocator, ucd: generate.Ucd, d: mappings.UnicodeData) ![]const u8 {
    var out: std.Io.Writer.Allocating = .init(gpa);
    const w = &out.writer;
    try w.print(
        \\//! The root collation of CLDR 49 (UCA {s}), from ucd/uca: allkeys_CLDR.txt's collation elements and contractions, allkeys.txt's implicit weight ranges, and PropList.txt's Unified_Ideograph.
        \\//!
        \\//! Generated by tools/generate.zig; `bay ucd` writes it again and
        \\//! `bay check-tables` checks it. Do not edit. The Unicode and CLDR data
        \\//! are under the Unicode License v3: see ../UNICODE-LICENSE.txt.
        \\
        \\const lookup = @import("../table.zig");
        \\
        \\
    , .{generate.version});

    const entries = try read(gpa, try ucd.read("uca/allkeys_CLDR.txt"), d);

    // Each entry's value: its one element inline, or its run of the
    // elements of entries with more than one, or that start contractions.
    var starts: std.AutoHashMapUnmanaged(u21, void) = .empty;
    for (entries) |e| if (e.code_points.len > 1) try starts.put(gpa, e.code_points[0], {});
    var elements: std.ArrayList(u32) = .empty;
    var runs: std.ArrayList(u32) = .empty;
    for (entries) |e| {
        if (e.elements.len > 31) return error.ExpansionTooLong;
        const starter = e.code_points.len == 1 and starts.contains(e.code_points[0]);
        if (e.elements.len == 1 and !starter) {
            try runs.append(gpa, e.elements[0] | 1 << 1);
        } else {
            try runs.append(gpa, @intCast(elements.items.len << 7 | e.elements.len << 2));
            try elements.appendSlice(gpa, e.elements);
        }
    }
    try w.writeAll(
        \\/// The collation elements of the entries with more than one, or that
        \\/// start contractions, packed: the primary weight in bits 16 to 31, the
        \\/// secondary in 7 to 15, the tertiary in 2 to 6, and in bit 0 whether it
        \\/// is variable (allkeys' `*`).
        \\
    );
    try w.print("pub const elements = [{d}]u32{{\n", .{elements.items.len});
    try generate.numbers(w, elements.items);
    try w.writeAll("};\n\n");

    // The single code points' runs, and which start a contraction.
    const values = try generate.filled(gpa, u32, 0);
    var starters: std.AutoHashMapUnmanaged(u21, std.ArrayList(usize)) = .empty;
    for (entries, 0..) |e, k| {
        if (e.code_points.len == 1) {
            values[e.code_points[0]] |= runs.items[k];
        } else {
            values[e.code_points[0]] |= 1;
            const got = try starters.getOrPut(gpa, e.code_points[0]);
            if (!got.found_existing) got.value_ptr.* = .empty;
            try got.value_ptr.append(gpa, k);
        }
    }
    try w.writeAll(
        \\/// Each code point's collation elements. With bit 1 set, its one element,
        \\/// packed as `elements` are but for that bit. Otherwise its run of
        \\/// `elements`, starting at bits 7 to 31 and as long as bits 2 to 6 say,
        \\/// and in bit 0 whether a contraction starts with it. 0: no entry
        \\/// (implicit weights) and no contraction.
        \\
    );
    try generate.writeShape(w, try generate.shape(gpa, values, 4, .smallest), "collation", "u32");
    try w.writeByte('\n');

    // Contractions: each starter, sorted, with its range of suffixes, each
    // sorted, the code points after the starter.
    var keys: std.ArrayList(u21) = .empty;
    var it = starters.keyIterator();
    while (it.next()) |k| try keys.append(gpa, k.*);
    std.mem.sort(u21, keys.items, {}, std.sort.asc(u21));
    try w.writeAll(
        \\/// Each code point a contraction starts with, sorted, and its range of
        \\/// `contractions`.
        \\pub const contraction_starters = [_]struct { u21, u16, u16 }{
        \\
    );
    var suffixes: std.ArrayList(struct { [max_contraction - 1]u21, u2, u32 }) = .empty;
    for (keys.items) |starter| {
        const list = starters.get(starter).?.items;
        const first = suffixes.items.len;
        for (list) |k| {
            const cps = entries[k].code_points;
            var suffix: [max_contraction - 1]u21 = @splat(0);
            @memcpy(suffix[0 .. cps.len - 1], cps[1..]);
            try suffixes.append(gpa, .{ suffix, @intCast(cps.len - 1), runs.items[k] });
        }
        std.mem.sort(@TypeOf(suffixes.items[0]), suffixes.items[first..], {}, struct {
            fn less(_: void, a: @TypeOf(suffixes.items[0]), b: @TypeOf(suffixes.items[0])) bool {
                return std.mem.order(u21, a[0][0..a[1]], b[0][0..b[1]]) == .lt;
            }
        }.less);
        try w.print("    .{{ 0x{x}, {d}, {d} }},\n", .{ starter, first, suffixes.items.len - first });
    }
    try w.writeAll(
        \\};
        \\
        \\/// The code points after a contraction's first (unused ones 0), how many
        \\/// there are, and the contraction's elements, packed as `collation`'s are.
        \\pub const contractions = [_]struct { [2]u21, u2, u32 }{
        \\
    );
    for (suffixes.items) |s| try w.print("    .{{ .{{ 0x{x}, 0x{x} }}, {d}, {d} }},\n", .{ s[0][0], s[0][1], s[1], s[2] });
    try w.writeAll("};\n\n");

    // Implicit weights (UTS #10 §10.1): the ranges with their own base, from
    // DUCET (allkeys_CLDR.txt does not repeat them), and Unified_Ideograph.
    try w.writeAll(
        \\/// The ranges of code points with implicit weights of their own (Tangut,
        \\/// Nushu, Khitan, ...): first, last, the base primary weight, and the
        \\/// code point the second weight counts from, the first of the first
        \\/// range with that base (UTS #10 §10.1.3).
        \\pub const implicit_ranges = [_]struct { u21, u21, u16, u21 }{
        \\
    );
    var lines = std.mem.splitScalar(u8, try ucd.read("uca/allkeys.txt"), '\n');
    var ranges: usize = 0;
    var origins: std.AutoHashMapUnmanaged(u16, u21) = .empty;
    while (lines.next()) |raw| {
        const prefix = "@implicitweights ";
        if (!std.mem.startsWith(u8, raw, prefix)) continue;
        const line = raw[prefix.len .. std.mem.findScalar(u8, raw, '#') orelse raw.len];
        const semicolon = std.mem.findScalar(u8, line, ';') orelse return error.BadImplicitWeights;
        const span = generate.trim(line[0..semicolon]);
        const dots = std.mem.find(u8, span, "..") orelse return error.BadImplicitWeights;
        const first = try std.fmt.parseInt(u21, span[0..dots], 16);
        const last = try std.fmt.parseInt(u21, span[dots + 2 ..], 16);
        const base = try std.fmt.parseInt(u16, generate.trim(line[semicolon + 1 ..]), 16);
        const origin = try origins.getOrPutValue(gpa, base, first);
        try w.print("    .{{ 0x{x}, 0x{x}, 0x{x}, 0x{x} }},\n", .{ first, last, base, origin.value_ptr.* });
        ranges += 1;
    }
    if (ranges == 0) return error.NoImplicitWeights;
    try w.writeAll(
        \\};
        \\
        \\/// Unified_Ideograph, as ranges.
        \\pub const unified_ideographs = [_][2]u21{
        \\
    );
    var props: generate.Lines = .init(try ucd.read("PropList.txt"));
    while (try props.next()) |l| if (std.mem.eql(u8, l.field(0), "Unified_Ideograph")) {
        try w.print("    .{{ 0x{x}, 0x{x} }},\n", .{ l.first, l.last });
    };
    try w.writeAll("};\n");
    return out.toOwnedSlice();
}

/// allkeys_CLDR.txt's entries for text in NFD, each element packed.
fn read(gpa: Allocator, text: []const u8, d: mappings.UnicodeData) ![]const Entry {
    var out: std.ArrayList(Entry) = .empty;
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |raw| {
        const line = generate.trim(raw[0 .. std.mem.findScalar(u8, raw, '#') orelse raw.len]);
        if (line.len == 0 or line[0] == '@') continue;
        const semicolon = std.mem.findScalar(u8, line, ';') orelse return error.BadEntry;
        var cps: std.ArrayList(u21) = .empty;
        var fields = std.mem.tokenizeScalar(u8, line[0..semicolon], ' ');
        while (fields.next()) |f| try cps.append(gpa, try std.fmt.parseInt(u21, f, 16));
        if (cps.items.len == 0 or cps.items.len > max_contraction) return error.BadEntry;
        var in_nfd = true;
        for (cps.items) |cp| if (decomposes(d, cp)) {
            in_nfd = false;
        };
        if (!in_nfd) continue;
        var elements: std.ArrayList(u32) = .empty;
        var rest = generate.trim(line[semicolon + 1 ..]);
        while (rest.len != 0) {
            // [.pppp.ssss.tttt] or [*pppp.ssss.tttt]
            if (rest.len < 17 or rest[0] != '[' or rest[16] != ']') return error.BadElement;
            const variable = rest[1] == '*';
            if (!variable and rest[1] != '.') return error.BadElement;
            const primary = try std.fmt.parseInt(u32, rest[2..6], 16);
            const secondary = try std.fmt.parseInt(u32, rest[7..11], 16);
            const tertiary = try std.fmt.parseInt(u32, rest[12..16], 16);
            if (secondary >= 1 << 9 or tertiary >= 1 << 5) return error.WeightTooLarge;
            try elements.append(gpa, primary << 16 | secondary << 7 | tertiary << 2 | @intFromBool(variable));
            rest = generate.trim(rest[17..]);
        }
        if (elements.items.len == 0) return error.BadEntry;
        try out.append(gpa, .{ .code_points = cps.items, .elements = elements.items });
    }
    return out.toOwnedSlice(gpa);
}

/// Whether a code point is not its own NFD: it has a canonical
/// decomposition, or is a Hangul syllable.
fn decomposes(d: mappings.UnicodeData, cp: u21) bool {
    if (cp >= 0xac00 and cp <= 0xd7a3) return true;
    const raw = d.decomposition[cp] orelse return false;
    return !raw.compatibility;
}
